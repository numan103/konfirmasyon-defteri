import assert from 'node:assert/strict';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
const arg = k => process.argv.find(s => s.startsWith(`--${k}=`))?.slice(k.length + 3);
const { chromium } = await import(pathToFileURL(path.resolve(arg('playwright'))));
const browser = await chromium.launch({ executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe', headless:true });
try {
  const page = await browser.newPage({ viewport:{ width:1440,height:1000 } });
  page.on('pageerror', error => console.error('PAGEERROR', error.message));
  page.on('console', message => { if (message.type() === 'error') console.error('CONSOLE', message.text()); });
  const requests = [];
  await page.route('**/api/**', route => {
    requests.push({ url:route.request().url(), method:route.request().method() });
    if (new URL(route.request().url()).searchParams.has('image')) return route.fulfill({ contentType:'image/png', body:Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aF1sAAAAASUVORK5CYII=', 'base64') });
    return route.fulfill({ json:{ ok:true, admin:false, tier:'free', access:'results', records:[{ id:'r1',coin:'GOLD',r:2,date:100,text:'PRIVATE_DESCRIPTION',imageCount:1 }] } });
  });
  await page.goto(arg('url') || 'http://127.0.0.1:4186');
  await page.waitForSelector('#admin-preview-open', { state:'attached' });
  assert.equal(await page.locator('#admin-preview-open').isVisible(), false);
  await page.evaluate(() => {
    AUTH.user = { id:'preview-admin', email:ADMIN_EMAIL };
    SITE.admin = true; SITE.tier = 'admin';
    document.getElementById('acc-admin-panel').style.display = 'block';
    document.body.classList.remove('landed'); document.getElementById('landing').classList.remove('open');
    showPage('erisim', true);
    document.getElementById('acc-admin-panel').style.display = 'block';
  });
  await page.locator('#admin-preview-open').click();
  const dialog = page.locator('dialog.admin-preview');
  const status = dialog.locator('[role=status]');
  await status.filter({ hasText:'Gerçek hesabın değişmedi' }).waitFor();
  assert.equal(await dialog.locator('iframe').getAttribute('sandbox'), '');
  const previewFrame = await (await dialog.locator('iframe').elementHandle()).contentFrame();
  const frame = () => previewFrame;
  await frame().locator('#landing.open').waitFor();
  assert.equal(await frame().locator('#landing.open').count(), 1);
  assert.equal(await frame().locator('script').count(), 0);
  await dialog.getByLabel('Üye görünümü').selectOption('free');
  await status.filter({ hasText:'Yeni üye · Gerçek hesabın değişmedi' }).waitFor();
  assert.equal(await frame().locator('#page-home').evaluate(n => n.classList.contains('hidden')), false);
  assert.equal(await frame().locator('#page-home').isVisible(), true);
  assert.equal(await dialog.getByLabel('Önizleme sayfası').locator('option[value=egitim]').count(), 0);
  await dialog.getByLabel('Önizleme sayfası').selectOption('alfatrading');
  await status.filter({ hasText:'Gerçek hesabın değişmedi' }).waitFor();
  assert.match(await frame().locator('body').innerText(), /GOLD/);
  assert.doesNotMatch(await frame().locator('body').innerText(), /PRIVATE_DESCRIPTION/);
  assert.equal(requests.some(r => r.url.includes('&image=')), false);
  assert.equal(await frame().locator('#acc-admin-panel').count(), 0);
  assert.equal(await frame().evaluate(() => { try { localStorage.setItem('preview','x'); return true; } catch { return false; } }), false);
  await dialog.getByLabel('Üye görünümü').selectOption('premium');
  await status.filter({ hasText:'Premium üye · Gerçek hesabın değişmedi' }).waitFor();
  assert.match(await frame().locator('body').innerText(), /PRIVATE_DESCRIPTION/);
  assert.equal(await frame().locator('.mentor-trade img[src^="data:image/png"]').count(), 1);
  assert.equal(await dialog.getByLabel('Önizleme sayfası').locator('option[value=egitim]').count(), 1);
  assert.equal(await dialog.getByLabel('Önizleme sayfası').locator('option[value=alfacharts]').count(), 0);
  assert.equal(await page.evaluate(() => SITE.admin && SITE.tier === 'admin' && AUTH.user.id === 'preview-admin'), true);
  if (arg('screenshot')) await dialog.screenshot({ path:path.resolve(arg('screenshot')) });
  await page.setViewportSize({ width:390,height:844 });
  assert.equal(await dialog.evaluate(n => n.getBoundingClientRect().width <= innerWidth), true);
  await dialog.getByRole('button', { name:'Yöneticiye dön ×' }).click();
  assert.equal(await dialog.evaluate(n => n.open), false);
  await page.locator('#admin-preview-open').click();
  await page.evaluate(() => { SITE.admin = false; AUTH.user = null; document.body.classList.add('landed'); });
  await page.waitForFunction(() => !document.querySelector('dialog.admin-preview').open);
  assert.equal(await page.locator('#admin-preview-open').isVisible(), false);
  const previewRequests = requests.filter(r => r.url.includes('mentorTrades'));
  assert.ok(previewRequests.some(r => r.url.includes('results=1')));
  assert.equal(previewRequests.every(r => r.method === 'GET'), true);
  console.log(JSON.stringify({ passed:true, isolated:true, freeProjection:true, premium:true, unchangedAdmin:true, mobile:true, productionWrites:false }));
} finally { await browser.close(); }

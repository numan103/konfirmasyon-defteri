export function calendarTitleTr(value) {
  const title = String(value || '').trim();
  const match = title.match(/^(.*?)(?: (m\/m|y\/y|q\/q|ytd\/y))?$/);
  const base = match?.[1] || title;
  const suffix = { 'm/m': ' (aylık)', 'y/y': ' (yıllık)', 'q/q': ' (çeyreklik)', 'ytd/y': ' (yılbaşından bu yana/yıllık)' }[match?.[2]] || '';
  if (Object.hasOwn(names, base)) return names[base] + suffix;
  const speech = title.match(/^(Fed Chair(?:man)?|ECB President|BOE Gov(?:ernor)?|BOC Gov(?:ernor)?|RBA Gov(?:ernor)?|RBNZ Gov(?:ernor)?|SNB Chairman) (.+) Speaks$/i);
  if (speech) return speech[1].replace(/Fed Chair(?:man)?/i, 'Fed Başkanı').replace(/ECB President/i, 'ECB Başkanı').replace(/ Gov(?:ernor)?| Chairman/i, ' Başkanı') + ' ' + speech[2] + ' Konuşması';
  const member = title.match(/^(FOMC Member|MPC Member|Gov Council Member|German Buba President) (.+) Speaks$/i);
  if (member) return ({ 'fomc member': 'FOMC Üyesi', 'mpc member': 'Para Politikası Kurulu Üyesi', 'gov council member': 'Yönetim Konseyi Üyesi', 'german buba president': 'Almanya Merkez Bankası Başkanı' }[member[1].toLowerCase()]) + ' ' + member[2] + ' Konuşması';
  return null;
}
